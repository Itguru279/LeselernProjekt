// Wortschatz der App. Jedes Wort mit Bild (Emoji) kann in Bild-Aufgaben
// vorkommen. Ob ein Wort an einem Tag benutzt wird, entscheidet allein der
// Prüfer: nur Wörter aus bekannten Lauten werden dem Kind gezeigt.
//
// Neue Wörter einfach unten ergänzen. Die Tests prüfen, dass jedes Wort
// zerlegbar ist und kein Bild doppelt vorkommt.

export type WordKind = 'nomen' | 'name' | 'wort';

export interface Word {
  text: string;
  kind: WordKind;
  img?: string; // Emoji als Bild; nur eindeutige Bilder verwenden
}

const nomen = (text: string, img: string): Word => ({ text, kind: 'nomen', img });
const name = (text: string, img?: string): Word => ({ text, kind: 'name', img });
const wort = (text: string): Word => ({ text, kind: 'wort' });

